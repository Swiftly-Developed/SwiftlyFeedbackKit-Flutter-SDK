/// Encode-direction contract against the server's own request corpus.
///
/// `request-wire-corpus.json` is generated by the server's encoder. These
/// tests fail when the client emits a key the server will not bind.
void main() {
  final requestCorpus = jsonDecode(
    File('test/fixtures/request-wire-corpus.json').readAsStringSync(),
  ) as Map<String, dynamic>;

  group('create feedback', () {
    test('emits the server canon keys, including user_email', () {
      final canon = requestCorpus['create_feedback'] as Map<String, dynamic>;

      const request = CreateFeedbackRequest(
        title: 'Add a dark theme',
        description: 'The list is hard to read at night.',
        category: FeedbackCategory.featureRequest,
        email: 'fixture-user@example.invalid',
        subscribeToMailingList: true,
        mailingListEmailTypes: ['status_change'],
      );
      final emitted = request.toJson();

      expect(emitted['title'], canon['title']);
      expect(emitted['description'], canon['description']);
      expect(emitted['category'], canon['category']);
      expect(emitted['user_email'], canon['user_email']);
      expect(
        emitted['subscribe_to_mailing_list'],
        canon['subscribe_to_mailing_list'],
      );
      expect(
        emitted['mailing_list_email_types'],
        canon['mailing_list_email_types'],
      );
      expect(emitted.containsKey('email'), isFalse);
      expect(emitted.containsKey('subscribeToMailingList'), isFalse);
      expect(emitted.containsKey('mailingListEmailTypes'), isFalse);
    });

    test('create posts user_id from the configured user', () async {
      final captured = await _capture((client) {
        return FeedbackApi(client).create(
          const CreateFeedbackRequest(
            title: 'Add a dark theme',
            description: 'The list is hard to read at night.',
            category: FeedbackCategory.featureRequest,
            email: 'fixture-user@example.invalid',
          ),
        );
      });

      expect(captured.method, 'POST');
      expect(captured.url.path, endsWith('/feedbacks'));
      final body = jsonDecode(captured.body) as Map<String, dynamic>;
      expect(body['user_id'], 'fixture-end-user');
      expect(body.containsKey('userId'), isFalse);
      expect(body['user_email'], 'fixture-user@example.invalid');
    });
  });

  group('vote', () {
    test('posts user_id and the mailing-list canon keys', () async {
      final canon = requestCorpus['create_vote'] as Map<String, dynamic>;
      final captured = await _capture(
        (client) => VotesApi(client).vote(
          '77777777-7777-4777-8777-777777777777',
          subscribeToMailingList: true,
          mailingListEmailTypes: const ['status_change'],
        ),
        responseBody: jsonEncode(const {
          'feedback_id': '77777777-7777-4777-8777-777777777777',
          'vote_count': 8,
          'has_voted': true,
        }),
      );

      expect(captured.method, 'POST');
      final body = jsonDecode(captured.body) as Map<String, dynamic>;
      expect(body['user_id'], canon['user_id']);
      expect(
        body['subscribe_to_mailing_list'],
        canon['subscribe_to_mailing_list'],
      );
      expect(
        body['mailing_list_email_types'],
        canon['mailing_list_email_types'],
      );
      expect(body.containsKey('userId'), isFalse);
      expect(body.containsKey('subscribeToMailingList'), isFalse);
      expect(body.containsKey('mailingListEmailTypes'), isFalse);
    });

    test('refuses to vote when no user id is configured', () async {
      var sent = false;
      final client = MockClient((_) async {
        sent = true;
        return http.Response('{}', 500);
      });
      final api = VotesApi(
        FeedbackKitHttpClient(
          config: const FeedbackKitConfig(apiKey: 'fixture-key'),
          client: client,
        ),
      );

      await expectLater(
        api.vote('77777777-7777-4777-8777-777777777777'),
        throwsA(isA<ValidationError>()),
      );
      expect(sent, isFalse);
    });
  });

  group('unvote', () {
    test('sends user_id in the DELETE body, not the query string', () async {
      final canon = requestCorpus['create_vote'] as Map<String, dynamic>;
      final captured = await _capture(
        (client) => VotesApi(client).unvote(
          '77777777-7777-4777-8777-777777777777',
        ),
        responseBody: jsonEncode(const {
          'feedback_id': '77777777-7777-4777-8777-777777777777',
          'vote_count': 7,
          'has_voted': false,
        }),
      );

      expect(captured.method, 'DELETE');
      expect(captured.url.path, endsWith('/votes'));
      expect(captured.url.queryParameters, isEmpty);
      final body = jsonDecode(captured.body) as Map<String, dynamic>;
      expect(body['user_id'], canon['user_id']);
      expect(body.containsKey('userId'), isFalse);
    });

    test('refuses to call the server when no user id is configured', () async {
      var sent = false;
      final client = MockClient((_) async {
        sent = true;
        return http.Response('{}', 500);
      });
      final api = VotesApi(
        FeedbackKitHttpClient(
          config: const FeedbackKitConfig(apiKey: 'fixture-key'),
          client: client,
        ),
      );

      await expectLater(
        api.unvote('77777777-7777-4777-8777-777777777777'),
        throwsA(isA<ValidationError>()),
      );
      expect(sent, isFalse);
    });
  });

  group('track event', () {
    test('posts event_name, user_id, and string properties', () async {
      final canon = requestCorpus['track_view_event'] as Map<String, dynamic>;
      final captured = await _capture(
        (client) => EventsApi(client).trackEvent(
          'feedback_list',
          properties: const {'source': 'fixture-tab', 'step_count': 5},
        ),
        responseBody: jsonEncode(const {
          'id': 'BBBBBBBB-BBBB-4BBB-8BBB-BBBBBBBBBBBB',
          'event_name': 'feedback_list',
          'user_id': 'fixture-end-user',
          'created_at': '2023-11-15T00:13:20Z',
        }),
      );

      expect(captured.method, 'POST');
      expect(captured.url.path, endsWith('/events/track'));
      final body = jsonDecode(captured.body) as Map<String, dynamic>;
      expect(body['event_name'], canon['event_name']);
      expect(body['user_id'], canon['user_id']);
      expect(body['properties'], {
        'source': 'fixture-tab',
        'step_count': '5',
      });
      expect(body.containsKey('name'), isFalse);
      expect(body.containsKey('timestamp'), isFalse);
    });

    test('refuses to track when no user id is configured', () async {
      var sent = false;
      final client = MockClient((_) async {
        sent = true;
        return http.Response('{}', 500);
      });
      final api = EventsApi(
        FeedbackKitHttpClient(
          config: const FeedbackKitConfig(apiKey: 'fixture-key'),
          client: client,
        ),
      );

      await expectLater(
        api.track(const TrackedEvent(name: 'feedback_list')),
        throwsA(isA<ValidationError>()),
      );
      expect(sent, isFalse);
    });

    test('decodes the server event payload', () {
      final corpus = jsonDecode(
        File('test/fixtures/event-wire-corpus.json').readAsStringSync(),
      ) as List<dynamic>;
      final row = corpus[0] as Map<String, dynamic>;

      final event = TrackedEvent.fromJson(row);

      expect(event.name, row['event_name']);
      expect(event.properties, row['properties']);
      expect(event.timestamp, DateTime.parse(row['created_at'] as String));
    });
  });

  group('feedback response', () {
    test('reads user_email and leaves it null when the server omits it', () {
      final corpus = jsonDecode(
        File('test/fixtures/feedback-wire-corpus.json').readAsStringSync(),
      ) as List<dynamic>;
      final withEmail = FeedbackItem.fromJson(
        corpus[0] as Map<String, dynamic>,
      );
      final withoutEmail = FeedbackItem.fromJson(
        corpus[1] as Map<String, dynamic>,
      );

      expect(withEmail.userEmail, 'fixture-user@example.invalid');
      expect(withoutEmail.userEmail, isNull);
    });
  });
}

Future<http.Request> _capture(
  Future<void> Function(FeedbackKitHttpClient client) send, {
  String? responseBody,
}) async {
  http.Request? captured;
  final client = MockClient((outgoing) async {
    captured = outgoing;
    return http.Response(
      responseBody ??
          jsonEncode(const {
            'id': '11111111-1111-4111-8111-111111111111',
            'title': 'Add a dark theme',
            'description': 'The list is hard to read at night.',
            'status': 'pending',
            'category': 'feature_request',
            'vote_count': 1,
            'has_voted': true,
            'comment_count': 0,
            'user_id': 'fixture-end-user',
            'created_at': '2023-11-14T22:13:20Z',
            'updated_at': '2023-11-14T23:13:20Z',
          }),
      200,
      headers: const {'content-type': 'application/json'},
    );
  });
  final httpClient = FeedbackKitHttpClient(
    config: const FeedbackKitConfig(
      apiKey: 'fixture-key',
      userId: 'fixture-end-user',
    ),
    client: client,
  );

  await send(httpClient);
  expect(captured, isNotNull);
  return captured!;
}
